const generateHistory = (baseNorm: number, variance: number) => {
  const times = ['10m ago', '8m ago', '6m ago', '4m ago', '2m ago', 'Just now'];
  return times.map((t, idx) => {
    const val = Math.min(100, Math.max(0, baseNorm + (idx - 2) * variance + (Math.random() * 4 - 2)));
    return {
      timestamp: t,
      rawValue: Math.round(val * 1.5),
      normalizedValue: Math.round(val),
    };
  });
};

